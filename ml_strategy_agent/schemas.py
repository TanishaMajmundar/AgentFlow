"""
schemas.py
----------
Pydantic data models (typed contracts) shared across all ML Strategy Agent modules.
These define the I/O structure between agents and internal components.
"""

from __future__ import annotations
from typing import Optional
from pydantic import BaseModel, Field
from enum import Enum


# ── Enumerations ────────────────────────────────────────────────────────────

class ProblemType(str, Enum):
    BINARY_CLASSIFICATION     = "binary_classification"
    MULTICLASS_CLASSIFICATION = "multiclass_classification"
    REGRESSION                = "regression"
    UNKNOWN                   = "unknown"


class DatasetSize(str, Enum):
    SMALL  = "small"   # < 1,000 rows
    MEDIUM = "medium"  # 1,000 – 50,000 rows
    LARGE  = "large"   # > 50,000 rows


class BalanceStatus(str, Enum):
    BALANCED       = "balanced"        # minority class >= 30%
    IMBALANCED     = "imbalanced"      # minority class < 30%
    NOT_APPLICABLE = "not_applicable"  # regression


# ── Data Agent Output (what Member 3 provides) ──────────────────────────────

class TargetDistribution(BaseModel):
    """Class counts for classification, or basic stats for regression."""
    class_counts: Optional[dict[str, int]] = Field(
        default=None,
        description="For classification: {class_label: count}"
    )
    min_value:   Optional[float] = Field(default=None, description="For regression")
    max_value:   Optional[float] = Field(default=None, description="For regression")
    mean_value:  Optional[float] = Field(default=None, description="For regression")


class PreprocessingSummary(BaseModel):
    missing_values_handled:  bool          = True
    categorical_encoded:     bool          = True
    numerical_scaled:        bool          = True
    text_features_processed: bool          = False
    notes:                   Optional[str] = None


class DatasetMetadata(BaseModel):
    """Raw metadata produced by the Data Agent."""
    num_rows:                 int
    num_columns:              int
    num_numeric_features:     int
    num_categorical_features: int
    num_text_features:        int = 0
    num_missing_values:       int = 0
    target_column:            str
    target_distribution:      TargetDistribution
    preprocessing:            PreprocessingSummary


class DataAgentOutput(BaseModel):
    """Complete output handed off from the Data Agent (Member 3)."""
    dataset_name: Optional[str] = "Unnamed Dataset"
    metadata:     DatasetMetadata


# ── Internal Analysis Models ─────────────────────────────────────────────────

class DatasetSummary(BaseModel):
    """Derived, human-friendly summary of dataset characteristics."""
    size_category:        DatasetSize
    num_rows:             int
    num_features:         int
    has_numeric:          bool
    has_categorical:      bool
    has_text:             bool
    has_missing_values:   bool
    balance_status:       BalanceStatus
    minority_class_ratio: Optional[float] = None  # None for regression
    imbalance_ratio:      Optional[float] = None  # majority:minority


# ── Strategy Output Models ────────────────────────────────────────────────────

class CandidateModel(BaseModel):
    """A recommended ML algorithm with its suitability score and rationale."""
    name:              str
    role:              str           # e.g. "Baseline", "Primary Candidate"
    suitability_score: int           # 0–100 (recommendation fit, NOT predicted accuracy)
    reasons:           list[str]     # Why this model was chosen


class MetricSet(BaseModel):
    """Selected evaluation metrics."""
    primary_metric:      str
    secondary_metrics:   list[str]
    validation_strategy: str
    num_folds:           Optional[int] = None


class ExperimentStep(BaseModel):
    step_number:  int
    description:  str


class ExperimentPlan(BaseModel):
    """Step-by-step training and comparison plan for the Training Agent."""
    steps:            list[ExperimentStep]
    baseline_model:   str
    comparison_models: list[str]


class MLStrategy(BaseModel):
    """
    Final structured output of the ML Strategy Agent.
    This is passed to the Training Agent (Member 5).
    """
    problem_statement:   str
    target_column:       str
    problem_type:        ProblemType
    dataset_summary:     DatasetSummary
    candidate_models:    list[CandidateModel]
    metrics:             MetricSet
    experiment_plan:     ExperimentPlan
    gemini_explanation:  Optional[str] = Field(
        default=None,
        description="Human-readable explanation generated by Gemini"
    )
    openml_context:      Optional[dict] = Field(
        default=None,
        description="Meta-learning context from OpenML for the UI"
    )
